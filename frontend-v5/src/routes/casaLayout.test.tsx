import { screen, waitFor, within } from '@testing-library/react';
import { expect, it } from 'vitest';
import { PASSWORD_B, renderApp, seededBackend } from '../test/harness';

it('[mock] Casa mette le azioni prima dei dettagli e aprire il ruolo non scrive dati', async () => {
  const { backend, homeB1,b,a } = seededBackend();
  await backend.seedDocument({homeId:homeB1.id,uploaderId:b.id,name:'Casa pending source',workflowState:'review'});
  await backend.seedDocument({homeId:homeB1.id,uploaderId:b.id,name:'Casa completed source',workflowState:'completed'});
  for(let i=0;i<26;i++)await backend.seedDocument({homeId:homeB1.id,uploaderId:b.id,name:'Compile '+i,workflowState:'to_compile'});
  await backend.seedDocument({homeId:homeB1.id,uploaderId:a.id,name:'Private other account',workflowState:'review'});
  const app = renderApp({ path: '/accedi', backend });
  await screen.findByRole('heading', { name: 'Accedi' });
  await app.user.type(screen.getByLabelText('Email'), 'b@example.test');
  await app.user.type(screen.getByLabelText('Password'), PASSWORD_B);
  await app.user.click(screen.getByRole('button', { name: 'Accedi' }));
  await screen.findByRole('heading', { level: 1, name: homeB1.name });
  expect(await screen.findByRole('link',{name:/Proposte da rivedere 1/})).toHaveAttribute('href',`/home/${homeB1.id}/documenti?workflow=review`);
  expect(screen.getByRole('link',{name:/Documenti da compilare 26/})).toHaveAttribute('href',`/home/${homeB1.id}/documenti?workflow=to_compile`);
  expect(screen.queryByText('Casa pending source')).not.toBeInTheDocument();expect(screen.queryByText('Private other account')).not.toBeInTheDocument();
  const explore=screen.getByRole('region',{name:'Esplora la casa'});
  expect(within(explore).getByRole('link',{name:/Documenti della casa/})).toHaveAttribute('href',`/home/${homeB1.id}/documenti?collection=house`);
  expect(within(explore).queryByRole('link',{name:/Rubrica/})).not.toBeInTheDocument();
  expect(within(explore).getAllByRole('link')).toHaveLength(3);
  expect(within(screen.getAllByRole('navigation',{name:'Sezioni di '+homeB1.name})[0]!).getAllByRole('link').map(link=>link.textContent)).toEqual(['Casa','Attività','Documenti','Spese','Rubrica']);
  const actions = screen.getByRole('region', { name: 'Azioni rapide' });
  expect(within(actions).getByRole('link', { name: 'Aggiungi documento' })).toHaveAttribute('href', `/home/${homeB1.id}/documenti?aggiungi=1`);
  expect(within(actions).getByRole('link', { name: 'Registra una spesa' })).toHaveAttribute('href', `/home/${homeB1.id}/spese?nuova-spesa=1`);
  expect(await screen.findByRole('link', { name: 'Apri le condivisioni' })).toHaveAttribute('href', `/home/${homeB1.id}/condivisioni`);
  await screen.findByText('Nessuna attività aperta.', { exact: false });
  const rooms = screen.getByRole('heading', { name: 'Esplora la casa' });
  expect(rooms.compareDocumentPosition(screen.getByRole('heading', { name: 'Condivisioni' })) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
  expect(screen.queryByText('Agenzie')).not.toBeInTheDocument();
  const summary = screen.getByText('Dettagli della casa e del tuo ruolo');
  const details = summary.closest('details')!;
  expect(details).not.toHaveAttribute('open');
  expect(screen.getByRole('region', { name: 'Da rivedere' }).compareDocumentPosition(summary) & Node.DOCUMENT_POSITION_FOLLOWING).toBeTruthy();
  const writes = () => backend.log.filter(r => r.method === 'POST').length;
  const before = writes();
  await app.user.click(summary);
  await waitFor(() => expect(details).toHaveAttribute('open'));
  expect(screen.getByRole('heading', { name: 'Dati della casa' })).toBeVisible();
  expect(writes()).toBe(before);
  expect(screen.queryByText('Benvenuto su Dimora')).toBeNull();
  await app.user.click(screen.getByRole('link',{name:/Proposte da rivedere 1/}));expect(await screen.findByRole('link',{name:'Casa pending source'})).toBeInTheDocument();expect(screen.queryByRole('link',{name:'Compile 0'})).not.toBeInTheDocument();
});
